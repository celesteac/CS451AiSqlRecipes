"""Build db/seed.sql and web/data/recipes.json from the Obsidian vault plus demo data.

Usage (from the repo root):
    python importer/build_seed.py [--vault vault/Recipes]
"""
import argparse
import json
import re
from datetime import date, timedelta
from pathlib import Path

import demo_data
from vault_parser import parse_quantity, parse_recipe_file

ROOT = Path(__file__).resolve().parent.parent
FILLER = {"large", "small", "medium", "ripe", "fresh", "plain", "dry", "grated", "chopped",
          "diced", "minced", "sliced", "softened", "melted", "packed", "firmly", "light",
          "pure", "ground", "of", "a", "some", "half", "box"}


def slugify(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def image_url(name):
    if not name:
        return None
    return "images/" + slugify(Path(name).stem) + Path(name).suffix.lower()


def fallback_ingredient(raw):
    """Ingredient name for lines the canonical list does not know."""
    _q, _u, rest = parse_quantity(raw)
    rest = re.sub(r"\(.*?\)", "", rest).split(",")[0]
    words = [w for w in re.findall(r"[a-zA-Z'’-]+", rest.lower()) if w not in FILLER]
    name = " ".join(words).strip()
    return re.sub(r"\b(to taste|for .*|optional)\b.*$", "", name).strip() or None


def sql(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


class Seed:
    def __init__(self):
        self.rows = {}  # table -> (columns, [values])

    def add(self, table, **cols):
        columns, values = self.rows.setdefault(table, (list(cols), []))
        values.append([cols[c] for c in columns])

    def to_sql(self, order):
        out = ["-- Generated by importer/build_seed.py. Do not edit by hand.", "BEGIN;"]
        for table in order:
            if table not in self.rows:
                continue
            columns, values = self.rows[table]
            out.append(f"\nINSERT INTO {table} ({', '.join(columns)}) VALUES")
            out.append(",\n".join("  (" + ", ".join(sql(v) for v in row) + ")" for row in values) + ";")
        for table, pk in IDENTITY_COLUMNS.items():
            if table in self.rows:
                out.append(f"SELECT setval(pg_get_serial_sequence('{table}', '{pk}'), "
                           f"(SELECT MAX({pk}) FROM {table}));")
        out.append("COMMIT;")
        return "\n".join(out) + "\n"


IDENTITY_COLUMNS = {
    "app_user": "user_id", "recipe": "recipe_id", "category": "category_id",
    "cuisine": "cuisine_id", "tag": "tag_id", "ingredient": "ingredient_id",
    "recipe_ingredient": "recipe_ingredient_id", "recipe_step": "recipe_step_id",
    "recipe_note": "recipe_note_id", "recipe_image": "recipe_image_id",
    "cook_log": "cook_log_id", "collection": "collection_id",
}
TABLE_ORDER = ["app_user", "category", "cuisine", "tag", "ingredient", "recipe",
               "recipe_category", "recipe_cuisine", "recipe_tag", "recipe_ingredient",
               "recipe_step", "recipe_equipment", "recipe_note", "recipe_image", "recipe_share",
               "cook_log", "saved_recipe", "collection", "collection_recipe"]


def build(vault_dir: Path):
    seed = Seed()
    users = {}
    for i, (username, display, bio) in enumerate(demo_data.USERS, start=1):
        users[username] = i
        seed.add("app_user", user_id=i, username=username, display_name=display, bio=bio,
                 created_at=f"2026-06-{i:02d}")

    lookups = {"category": {}, "cuisine": {}, "tag": {}, "ingredient": {}}

    def lookup(table, name):
        ids = lookups[table]
        if name not in ids:
            ids[name] = len(ids) + 1
            seed.add(table, **{f"{table}_id": ids[name], "name": name})
        return ids[name]

    # Gather (owner, parsed recipe, visibility)
    entries = []
    for path in sorted(vault_dir.glob("*.md")):
        r = parse_recipe_file(path)
        entries.append(("celeste", r, demo_data.VAULT_VISIBILITY.get(r["title"], "public")))
    for user_dir in sorted((ROOT / "demo_recipes").iterdir()):
        for path in sorted(user_dir.glob("*.md")):
            r = parse_recipe_file(path)
            vis = demo_data.DEMO_VISIBILITY.get((user_dir.name, r["title"]), "public")
            entries.append((user_dir.name, r, vis))

    recipe_ids = {}
    counters = {"ri": 0, "step": 0, "note": 0, "img": 0, "log": 0}
    export = []
    base_day = date(2026, 6, 15)
    for rid, (owner, r, vis) in enumerate(entries, start=1):
        recipe_ids[(owner, r["title"])] = rid
    for rid, (owner, r, vis) in enumerate(entries, start=1):
        fork = demo_data.FORKS.get((owner, r["title"]))
        created = (base_day + timedelta(days=rid * 3)).isoformat()
        seed.add("recipe", recipe_id=rid, owner_id=users[owner],
                 forked_from_recipe_id=recipe_ids[fork] if fork else None,
                 title=r["title"], slug=slugify(r["title"]), description=r["description"],
                 visibility=vis, prep_minutes=r["prep_minutes"], cook_minutes=r["cook_minutes"],
                 total_minutes=r["total_minutes"], yield_text=r["yield_text"],
                 servings=r["servings"], kcal_per_serving=r["kcal_per_serving"],
                 nutrition_text=r["nutrition_text"], source_name=r["source_name"],
                 source_url=r["source_url"], cover_image_url=image_url(r["cover_image"]),
                 created_at=created, updated_at=created)
        for c in r["categories"]:
            seed.add("recipe_category", recipe_id=rid, category_id=lookup("category", c))
        for c in r["cuisines"]:
            seed.add("recipe_cuisine", recipe_id=rid, cuisine_id=lookup("cuisine", c))
        for t in r["tags"]:
            seed.add("recipe_tag", recipe_id=rid, tag_id=lookup("tag", t))
        ingredients = []
        for ing in r["ingredients"]:
            counters["ri"] += 1
            name = ing["ingredient"] or fallback_ingredient(ing["raw_text"])
            seed.add("recipe_ingredient", recipe_ingredient_id=counters["ri"], recipe_id=rid,
                     ingredient_id=lookup("ingredient", name) if name else None,
                     section=ing["section"], position=ing["position"],
                     quantity=ing["quantity"], unit=ing["unit"], raw_text=ing["raw_text"])
            ingredients.append({"section": ing["section"], "text": ing["raw_text"], "ingredient": name})
        for s in r["steps"]:
            counters["step"] += 1
            seed.add("recipe_step", recipe_step_id=counters["step"], recipe_id=rid,
                     section=s["section"], position=s["position"], body=s["body"])
        for i, e in enumerate(r["equipment"], start=1):
            seed.add("recipe_equipment", recipe_id=rid, position=i, name=e)
        notes = []
        for n in r["notes"]:
            counters["note"] += 1
            seed.add("recipe_note", recipe_note_id=counters["note"], recipe_id=rid,
                     author_id=users[owner], title=n["title"], body=n["body"], created_at=created)
            notes.append({"author": owner, "title": n["title"], "body": n["body"]})
        for img in r["images"]:
            counters["img"] += 1
            seed.add("recipe_image", recipe_image_id=counters["img"], recipe_id=rid,
                     kind="original", url=image_url(img))
        if owner == "celeste" and r["made_it"]:
            counters["log"] += 1
            seed.add("cook_log", cook_log_id=counters["log"], user_id=users["celeste"],
                     recipe_id=rid, cooked_on=None, rating=None, comment="From vault: I made it")
        export.append({
            "id": rid, "owner": owner, "title": r["title"], "slug": slugify(r["title"]),
            "visibility": vis, "description": r["description"],
            "forked_from": recipe_ids.get(fork) if fork else None,
            "prep_minutes": r["prep_minutes"], "cook_minutes": r["cook_minutes"],
            "total_minutes": r["total_minutes"], "yield_text": r["yield_text"],
            "servings": r["servings"], "kcal_per_serving": r["kcal_per_serving"],
            "nutrition_text": r["nutrition_text"], "source_name": r["source_name"],
            "source_url": r["source_url"], "cover_image_url": image_url(r["cover_image"]),
            "images": [image_url(i) for i in r["images"]],
            "categories": r["categories"], "cuisines": r["cuisines"], "tags": r["tags"],
            "ingredients": ingredients, "steps": r["steps"], "equipment": r["equipment"],
            "notes": notes, "ratings": [],
        })

    by_id = {e["id"]: e for e in export}
    for recipe, user, perm, at in demo_data.SHARES:
        seed.add("recipe_share", recipe_id=recipe_ids[recipe], shared_with_user_id=users[user],
                 permission=perm, shared_at=at)
    for user, recipe, at in demo_data.SAVES:
        seed.add("saved_recipe", user_id=users[user], recipe_id=recipe_ids[recipe], saved_at=at)
    for user, recipe, on, rating, comment in demo_data.COOK_LOGS:
        counters["log"] += 1
        seed.add("cook_log", cook_log_id=counters["log"], user_id=users[user],
                 recipe_id=recipe_ids[recipe], cooked_on=on, rating=rating, comment=comment)
        if rating:
            by_id[recipe_ids[recipe]]["ratings"].append(rating)
    for author, recipe, body, at in demo_data.COMMENTS:
        counters["note"] += 1
        seed.add("recipe_note", recipe_note_id=counters["note"], recipe_id=recipe_ids[recipe],
                 author_id=users[author], title=None, body=body, created_at=at)
        by_id[recipe_ids[recipe]]["notes"].append({"author": author, "title": None, "body": body})
    for cid, (owner, name, desc, vis, recipes) in enumerate(demo_data.COLLECTIONS, start=1):
        seed.add("collection", collection_id=cid, owner_id=users[owner], name=name,
                 description=desc, visibility=vis, created_at="2026-09-01")
        for pos, recipe in enumerate(recipes, start=1):
            seed.add("collection_recipe", collection_id=cid, recipe_id=recipe_ids[recipe],
                     position=pos)

    # The static site shows what an anonymous visitor may see: public recipes only.
    names = {u: d for u, d, _ in demo_data.USERS}
    public = []
    for e in export:
        if e["visibility"] != "public":
            continue
        e = dict(e, owner_name=names[e["owner"]],
                 notes=[dict(n, author_name=names[n["author"]]) for n in e["notes"]])
        ratings = e.pop("ratings")
        e["avg_rating"] = round(sum(ratings) / len(ratings), 1) if ratings else None
        e["rating_count"] = len(ratings)
        if e["forked_from"] and by_id[e["forked_from"]]["visibility"] != "public":
            e["forked_from"] = None
        public.append(e)
    return seed, public


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vault", type=Path, default=ROOT / "vault" / "Recipes")
    args = parser.parse_args()
    seed, public = build(args.vault)
    (ROOT / "db" / "seed.sql").write_text(seed.to_sql(TABLE_ORDER), encoding="utf-8")
    out = ROOT / "web" / "data" / "recipes.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(public, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"Wrote db/seed.sql and {len(public)} public recipes to web/data/recipes.json")


if __name__ == "__main__":
    main()
