-- Recipe sharing database (PostgreSQL 15+ / Supabase)
-- Run order: schema.sql -> seed.sql -> (Supabase only) supabase.sql

DROP TABLE IF EXISTS collection_recipe, collection, saved_recipe, cook_log, recipe_share,
    recipe_image, recipe_note, recipe_equipment, recipe_step, recipe_ingredient, ingredient,
    recipe_tag, tag, recipe_cuisine, cuisine, recipe_category, category,
    recipe, app_user CASCADE;

-- People who use the site. auth_user_id links to Supabase auth.users once the person signs up.
CREATE TABLE app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id  UUID UNIQUE,
    username      TEXT NOT NULL UNIQUE,
    display_name  TEXT NOT NULL,
    email         TEXT UNIQUE,
    bio           TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A recipe is owned by exactly one user.
-- visibility: 'private' = owner and people it is shared with,
--             'unlisted' = anyone with the link, not shown in browse lists,
--             'public' = everyone.
CREATE TABLE recipe (
    recipe_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id              BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    forked_from_recipe_id BIGINT REFERENCES recipe(recipe_id) ON DELETE SET NULL,
    title                 TEXT NOT NULL,
    slug                  TEXT NOT NULL,
    description           TEXT,
    visibility            TEXT NOT NULL DEFAULT 'private'
                          CHECK (visibility IN ('private', 'unlisted', 'public')),
    prep_minutes          INTEGER CHECK (prep_minutes >= 0),
    cook_minutes          INTEGER CHECK (cook_minutes >= 0),
    total_minutes         INTEGER CHECK (total_minutes >= 0),
    yield_text            TEXT,          -- free text, e.g. '24 cookies', '1 loaf'
    servings              INTEGER CHECK (servings > 0),
    kcal_per_serving      INTEGER CHECK (kcal_per_serving >= 0),
    nutrition_text        TEXT,
    source_name           TEXT,          -- cookbook, person, or site name
    source_url            TEXT,
    cover_image_url       TEXT,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (owner_id, slug)
);

-- Broad course, e.g. meal, dessert, bread, snack or side. A recipe can have several.
CREATE TABLE category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE
);
CREATE TABLE recipe_category (
    recipe_id   BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES category(category_id) ON DELETE CASCADE,
    PRIMARY KEY (recipe_id, category_id)
);

-- e.g. Italian, Asian, Peruvian, American
CREATE TABLE cuisine (
    cuisine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL UNIQUE
);
CREATE TABLE recipe_cuisine (
    recipe_id  BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    cuisine_id BIGINT NOT NULL REFERENCES cuisine(cuisine_id) ON DELETE CASCADE,
    PRIMARY KEY (recipe_id, cuisine_id)
);

-- Free-form lowercase labels, e.g. cookie, chicken, pasta, halloween
CREATE TABLE tag (
    tag_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   TEXT NOT NULL UNIQUE
);
CREATE TABLE recipe_tag (
    recipe_id BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    tag_id    BIGINT NOT NULL REFERENCES tag(tag_id) ON DELETE CASCADE,
    PRIMARY KEY (recipe_id, tag_id)
);

-- Canonical ingredient names (lowercase, singular), e.g. 'butter', 'all-purpose flour', 'egg'
CREATE TABLE ingredient (
    ingredient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE
);

-- One ingredient line of a recipe. raw_text is the line as written;
-- quantity/unit are parsed from it when possible (NULL otherwise).
-- section groups lines, e.g. 'Icing' or 'Crumb Topping' (NULL = main list).
CREATE TABLE recipe_ingredient (
    recipe_ingredient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id            BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    ingredient_id        BIGINT REFERENCES ingredient(ingredient_id),
    section              TEXT,
    position             INTEGER NOT NULL,
    quantity             NUMERIC(8, 3),
    unit                 TEXT,          -- e.g. 'cup', 'tbsp', 'tsp', 'g', 'oz', 'lb'
    raw_text             TEXT NOT NULL,
    UNIQUE (recipe_id, position)
);

-- Ordered directions. section groups steps, e.g. 'Make the Dough'.
CREATE TABLE recipe_step (
    recipe_step_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id      BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    section        TEXT,
    position       INTEGER NOT NULL,
    body           TEXT NOT NULL,
    UNIQUE (recipe_id, position)
);

-- Tools needed, e.g. '9x9-inch metal baking pan', 'blender'
CREATE TABLE recipe_equipment (
    recipe_id BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    position  INTEGER NOT NULL,
    name      TEXT NOT NULL,
    PRIMARY KEY (recipe_id, position)
);

-- Tips and notes written about a recipe, by its owner or anyone who can see it.
CREATE TABLE recipe_note (
    recipe_note_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id      BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    author_id      BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    title          TEXT,
    body           TEXT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Extra photos besides the cover: 'original' = photo of the source recipe, 'made' = my result.
CREATE TABLE recipe_image (
    recipe_image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id       BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    kind            TEXT NOT NULL CHECK (kind IN ('original', 'made')),
    url             TEXT NOT NULL
);

-- Direct sharing of a recipe with another user. 'edit' also allows changing it.
CREATE TABLE recipe_share (
    recipe_id           BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    shared_with_user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    permission          TEXT NOT NULL DEFAULT 'view' CHECK (permission IN ('view', 'edit')),
    shared_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (recipe_id, shared_with_user_id)
);

-- Each time a user cooked a recipe, with an optional 1-5 star rating.
-- cooked_on is NULL when the date is unknown (e.g. the vault's "I made it: true").
CREATE TABLE cook_log (
    cook_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    recipe_id   BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    cooked_on   DATE,
    rating      SMALLINT CHECK (rating BETWEEN 1 AND 5),
    comment     TEXT
);

-- Bookmarks ("save for later") of other people's (or your own) recipes.
CREATE TABLE saved_recipe (
    user_id   BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    recipe_id BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    saved_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, recipe_id)
);

-- A named, ordered list of recipes, e.g. 'Meal Prep' or 'Halloween Party'.
CREATE TABLE collection (
    collection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    name          TEXT NOT NULL,
    description   TEXT,
    visibility    TEXT NOT NULL DEFAULT 'private'
                  CHECK (visibility IN ('private', 'unlisted', 'public')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (owner_id, name)
);
CREATE TABLE collection_recipe (
    collection_id BIGINT NOT NULL REFERENCES collection(collection_id) ON DELETE CASCADE,
    recipe_id     BIGINT NOT NULL REFERENCES recipe(recipe_id) ON DELETE CASCADE,
    position      INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (collection_id, recipe_id)
);

CREATE INDEX recipe_owner_idx ON recipe(owner_id);
CREATE INDEX recipe_visibility_idx ON recipe(visibility);
CREATE INDEX recipe_ingredient_ingredient_idx ON recipe_ingredient(ingredient_id);
CREATE INDEX recipe_share_user_idx ON recipe_share(shared_with_user_id);
CREATE INDEX cook_log_recipe_idx ON cook_log(recipe_id);
